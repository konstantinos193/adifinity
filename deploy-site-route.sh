#!/bin/bash
################################################################################
# Point nginx's adinfinity.gr vhost at one colour of the site, and prove nginx
# took it -- this box's edge is the SYSTEM nginx, not the staging Traefik.
#
#   bash deploy-site-route.sh <green|blue>
#
# Called by deploy-site.sh after the new colour's health check passes. Exits
# non-zero, leaving the previous file in force, when nginx does not confirm
# the change; the deploy then aborts before it stops the old colour.
#
# What it writes, /etc/nginx/sites-available/adinfinity.gr, is reloaded via
# `systemctl reload nginx` -- zero dropped connections.
#
# TLS: certs live in /etc/letsencrypt/live/<domain>/ (certbot, same as every
# other vhost on this box). Before the DNS flip there is no cert yet, so the
# script writes a port-80 vhost only; after the flip, `certbot --nginx`
# issues the cert and this script then writes the full 443+redirect pair.
################################################################################

set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

if [ "$#" -ne 1 ] || { [ "$1" != green ] && [ "$1" != blue ]; }; then
    echo "Usage: $0 <green|blue>" >&2
    exit 2
fi
COLOR=$1
CONTAINER=adifinity-site-$COLOR
if [ "$COLOR" = "green" ]; then PORT=3071; else PORT=3070; fi

SITE_DOMAIN=${SITE_DOMAIN:-adinfinity.gr}
WWW_DOMAIN=${WWW_DOMAIN:-www.$SITE_DOMAIN}
UPSTREAM=${UPSTREAM:-http://127.0.0.1:$PORT}
NGINX_AVAIL=${NGINX_AVAIL:-/etc/nginx/sites-available}
NGINX_ENABLED=${NGINX_ENABLED:-/etc/nginx/sites-enabled}
CERT_DIR=/etc/letsencrypt/live/$SITE_DOMAIN
TARGET="$NGINX_AVAIL/$SITE_DOMAIN"

mkdir -p "$NGINX_AVAIL"

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

if [ -f "$CERT_DIR/fullchain.pem" ]; then
    # Post-flip: certbot has issued the cert -> full certbot-style vhost.
    cat > "$TMP" <<EOF
# Generated by adifinity/deploy-site-route.sh on $(date -u '+%Y-%m-%d %H:%M:%S UTC').
# DO NOT EDIT BY HAND -- the next deploy overwrites it. Change the script.
#
# Live colour: $CONTAINER ($UPSTREAM)

server {
    server_name $SITE_DOMAIN $WWW_DOMAIN;

    client_max_body_size 10M;

    location / {
        proxy_pass $UPSTREAM;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_cache_bypass \$http_upgrade;

        proxy_connect_timeout 60s;
        proxy_send_timeout 120s;
        proxy_read_timeout 120s;
    }

    listen 443 ssl;
    ssl_certificate $CERT_DIR/fullchain.pem;
    ssl_certificate_key $CERT_DIR/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;
}
server {
    if (\$host = $SITE_DOMAIN) {
        return 301 https://\$host\$request_uri;
    }
    if (\$host = $WWW_DOMAIN) {
        return 301 https://\$host\$request_uri;
    }

    listen 80;
    server_name $SITE_DOMAIN $WWW_DOMAIN;
    return 404;
}
EOF
else
    # Pre-flip: no cert yet. Port-80 vhost so certbot --nginx can issue and
    # so the site is reachable over HTTP for early smoke tests.
    cat > "$TMP" <<EOF
# Generated by adifinity/deploy-site-route.sh on $(date -u '+%Y-%m-%d %H:%M:%S UTC').
# DO NOT EDIT BY HAND -- the next deploy overwrites it. Change the script.
#
# Live colour: $CONTAINER ($UPSTREAM)
# NOTE: no certificate at $CERT_DIR yet -- HTTP only until certbot --nginx runs.

server {
    listen 80;
    server_name $SITE_DOMAIN $WWW_DOMAIN;

    client_max_body_size 10M;

    location / {
        proxy_pass $UPSTREAM;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_cache_bypass \$http_upgrade;
    }
}
EOF
fi

# The previous file, kept until this one is proven: if nginx rejects the new
# config it goes back, so a failed deploy leaves the old colour serving.
cp -p "$TARGET" "$TARGET.prev" 2>/dev/null || true
restore_previous() {
    if [ -f "$TARGET.prev" ]; then
        mv "$TARGET.prev" "$TARGET"
        echo -e "${YELLOW}  Previous $TARGET restored${NC}"
    fi
}

install -m 0644 "$TMP" "$TARGET"
ln -sfn "$TARGET" "$NGINX_ENABLED/$SITE_DOMAIN"
echo -e "${GREEN}  ✓ $TARGET written ($CONTAINER via $UPSTREAM)${NC}"

if ! nginx -t >/dev/null 2>&1; then
    echo -e "${RED}✗ nginx -t failed on the new vhost${NC}"
    nginx -t 2>&1 | sed 's/^/    /'
    restore_previous
    nginx -t >/dev/null 2>&1 && systemctl reload nginx || true
    exit 1
fi

systemctl reload nginx
echo -e "${GREEN}  ✓ nginx reloaded${NC}"

if [ "${NGINX_ROUTE_VERIFY:-1}" = 0 ]; then
    exit 0
fi

# A real request through it: 502/504/000 mean nothing answered; anything else
# (a 404 on a missing page included) means the app did. --resolve pins the
# host to loopback; -k in case a stale/default cert is still in play.
status=""
scheme=https
[ -f "$CERT_DIR/fullchain.pem" ] || scheme=http
for _ in 1 2 3 4 5; do
    status=$(curl -sk -o /dev/null -w '%{http_code}' --max-time 15 \
        --resolve "$SITE_DOMAIN:$([ "$scheme" = https ] && echo 443 || echo 80):127.0.0.1" \
        "$scheme://$SITE_DOMAIN/" 2>/dev/null || true)
    case "$status" in
        502|503|504|000|"") sleep 2 ;;
        *)
            echo -e "${GREEN}  ✓ nginx serves $SITE_DOMAIN from $CONTAINER (HTTP $status)${NC}"
            rm -f "$TARGET.prev"
            break
            ;;
    esac
done
case "$status" in
    502|503|504|000|"")
        echo -e "${RED}✗ nginx loaded the vhost but the site does not answer through it (last: ${status:-none})${NC}"
        restore_previous
        systemctl reload nginx || true
        exit 1
        ;;
esac
